#now lets create a state



class CodeState(TypedDict):
    user_code: str
    generated_code: str
    review_feedback: str
    is_approved: bool
    iteration: int
    messages: Annotated[list, add_messages]
    
    
    
#nodes
    
grok_prompt = """
You are an expert Python Developer and Software Engineer.

Your responsibility is to generate, debug, and improve Python code.

You will receive:
1. Original code submitted by the user.
2. Review feedback from the previous review cycle.
3. Current iteration number.

Your tasks:

1. Analyze the original code and understand its purpose.
2. Identify bugs, logical errors, and implementation issues.
3. Consider the reviewer's feedback carefully.
4. Fix all identified issues.
5. Improve code readability, maintainability, and efficiency.
6. Preserve the original functionality and requirements.
7. Avoid unnecessary modifications.
8. Generate clean, executable Python code.

IMPORTANT RULES:

- Do not ignore previous review feedback.
- Do not introduce unnecessary dependencies.
- Do not remove important functionality.
- Do not fabricate test results.
- If the previous code is already correct, avoid unnecessary changes.

OUTPUT FORMAT:

Return ONLY the complete corrected Python code.

Do not include explanations, markdown code fences, or additional commentary.
"""



def generate_code(state: CodeState) -> dict:
    """Generate or improve Python code using Grok."""

    attempt = state.get("iteration", 0) + 1

    user_code = state["user_code"]
    previous_feedback = state.get("review_feedback", "")

    if attempt == 1:

        user_message = (
            f"Here is the Python code submitted by the user:\n\n"
            f"{user_code}\n\n"
            f"Analyze the code, identify bugs and generate "
            f"a corrected version.")
    else:

        previous_code = state["generated_code"]

        user_message = (
            f"Your previous generated code:\n\n"
            f"{previous_code}\n\n"
            f"The reviewer rejected your previous code.\n\n"
            f"Here is the reviewer's feedback:\n\n"
            f"{previous_feedback}\n\n"
            f"Generate a new, improved version that fixes "
            f"every issue mentioned in the feedback."
        )

    response = writer_llm.invoke([("system", grok_prompt),("human", user_message)])

    return {
        "generated_code": response.content,
        "iteration": attempt,
        "messages": [
            ("assistant", f"Code generated. Iteration: {attempt}")]}

    


