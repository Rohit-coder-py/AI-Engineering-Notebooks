import os
from typing import TypedDict, Annotated

from dotenv import load_dotenv

from langgraph.graph.message import add_messages
from langgraph.graph import StateGraph, START, END

from langchain_groq import ChatGroq
from langchain_google_genai import ChatGoogleGenerativeAI

load_dotenv()

grok_api_key = os.getenv("GROQ_API_KEY")
google_api_key = os.getenv("GOOGLE_API_KEY")


writer_llm = ChatGroq(
    model="openai/gpt-oss-20b",
    api_key=grok_api_key,
    temperature=0.2)

reviewer_google = ChatGoogleGenerativeAI(
    model="gemini-2.5-flash",
    google_api_key=google_api_key,
    temperature=0.1
)


MAX_ITERATIONS = 3



class CodeState(TypedDict):
    user_code: str
    generated_code: str
    review_feedback: str
    is_approved: bool
    iteration: int
    messages: Annotated[list, add_messages]


# prompts

grok_prompt = """
You are an expert Python Developer and Software Engineer.

Your responsibility is to generate, debug, and improve Python code.

You will receive:
1. Original code submitted by the user.
2. Review feedback from the previous review cycle.
3. Current iteration number.

YOUR TASKS:

1. Understand the original code and its purpose.
2. Identify bugs and logical errors.
3. Consider previous review feedback carefully.
4. Fix all identified issues.
5. Improve readability and maintainability.
6. Preserve original functionality.
7. Avoid unnecessary modifications.
8. Generate clean, executable Python code.

IMPORTANT RULES:

- Never ignore previous review feedback.
- Do not introduce unnecessary dependencies.
- Do not remove important functionality.
- Do not fabricate test results.
- Do not make unnecessary changes.

OUTPUT FORMAT:

Return ONLY the complete corrected Python code.

Do not include explanations or Markdown code fences.
"""


google_prompt = """
You are a Senior Python Code Reviewer and Software Quality Engineer.

Independently review the Python code generated by another AI model.

REVIEW CRITERIA:

1. Correctness:
   - Syntax errors
   - Logical errors
   - Incorrect implementations

2. Code Quality:
   - Readability
   - Maintainability
   - Naming conventions
   - Unnecessary complexity

3. Reliability:
   - Runtime errors
   - Edge cases
   - Unsafe implementations

4. Requirements:
   - Does the code fulfill the original requirements?

APPROVAL RULES:

- Approve only if the code satisfies the requirements.
- Reject code containing significant issues.
- Do not invent problems.
- Be specific about identified issues.

OUTPUT FORMAT:

STATUS: APPROVED or REJECTED

FEEDBACK:
Explain the issues found.
If no issues exist, write "No significant issues found."

SUGGESTED FIXES:
Provide specific recommendations.

IMPORTANT:
Review the actual code independently.
Do not assume the code is correct because another
AI model generated it.
"""


#NODE 1 - GENERATE CODE (GROK)


def generate_code(state: CodeState) -> dict:
    """Generate or improve Python code using Grok."""

    attempt = state.get("iteration", 0) + 1

    user_code = state["user_code"]
    previous_feedback = state.get("review_feedback", "")

    if attempt == 1:

        user_message = f"""
Original Python code submitted by the user:

{user_code}

Analyze the code and generate a corrected version.
"""

    else:

        previous_code = state["generated_code"]

        user_message = f"""
Your previous generated code:

{previous_code}

The reviewer rejected your previous code.

Reviewer's feedback:

{previous_feedback}

Generate an improved version that fixes all
the identified issues.

Original user requirements:

{user_code}
"""

    response = writer_llm.invoke([
        ("system", grok_prompt),
        ("human", user_message)
    ])

    generated_code = response.content.strip()

    return {
        "generated_code": generated_code,
        "iteration": attempt,
        "is_approved": False,
        "messages": [
            ("assistant", f"Grok generated code. Iteration: {attempt}")
        ]
    }


# NODE 2 - REVIEW CODE (GOOGLE)

def review_code(state: CodeState) -> dict:
    """Independently review generated code using Google."""

    user_message = f"""
ORIGINAL USER CODE AND REQUIREMENTS:

{state["user_code"]}


GENERATED PYTHON CODE:

{state["generated_code"]}


CURRENT ITERATION:

{state["iteration"]}

Review this code carefully.

Return your decision using the required format.
"""

    response = reviewer_google.invoke([
        ("system", google_prompt),
        ("human", user_message)
    ])

    review_result = response.content.strip()

    is_approved = (
        "STATUS: APPROVED" in review_result.upper()
        and "STATUS: REJECTED" not in review_result.upper()
    )

    return {
        "review_feedback": review_result,
        "is_approved": is_approved,
        "messages": [
            ("assistant", f"Google Review:\n{review_result}")
        ]
    }


#  cONDITIONAL ROUTING

def route_after_review(state: CodeState) -> str:
    """Decide whether to approve, retry, or stop."""

    if state["is_approved"]:
        return "approved"

    if state["iteration"] >= MAX_ITERATIONS:
        return "max_iterations"

    return "retry"


# BUILD LANGGRAPH WORKFLOW

workflow = StateGraph(CodeState)

# Register nodes
workflow.add_node("generate_code", generate_code)
workflow.add_node("review_code", review_code)

# Starting point
workflow.add_edge(START, "generate_code")

# Generation -> Review
workflow.add_edge("generate_code", "review_code")

# Review -> Approval or Retry
workflow.add_conditional_edges(
    "review_code",
    route_after_review,
    {
        "approved": END,
        "retry": "generate_code",
        "max_iterations": END
    }
)

# Compile graph
app = workflow.compile()


